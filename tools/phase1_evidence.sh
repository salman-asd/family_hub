#!/usr/bin/env bash
# H13: runs the whole Phase 1 verification on a clean Linux clone and writes
# docs/phase1_evidence.md (pass/fail and counts only).  Never edits code.
#
#   bash tools/phase1_evidence.sh
#
# Needs: Flutter (pinned in CI), Node 20+, Java 17 (Firestore emulator).
set -u
OUT=docs/phase1_evidence.md
LOG=$(mktemp -d)

{
  echo "# Phase 1 evidence (generated by tools/phase1_evidence.sh)"
  echo
  echo "- Date (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Commit: $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
  echo "- Flutter: $(flutter --version 2>/dev/null | head -n 1)"
  echo
  echo "| Check | Result | Summary (last lines of output) |"
  echo "| --- | --- | --- |"
} > "$OUT"

FAILED=0
run() {
  local name="$1"; shift
  local log="$LOG/$(echo "$name" | tr -c 'a-zA-Z0-9' _).log"
  if "$@" >"$log" 2>&1; then status="PASS"; else status="FAIL"; FAILED=1; fi
  local summary
  summary=$(tail -n 2 "$log" | tr '\n|' '  ' | cut -c1-160)
  echo "| $name | $status | $summary |" >> "$OUT"
}

run "flutter pub get"              flutter pub get
run "dart format"                  dart format --output=none --set-exit-if-changed .
run "flutter analyze"              flutter analyze
run "unit/widget tests (no golden)" flutter test --exclude-tags golden --coverage
run "golden tests"                 flutter test --tags golden
run "check_indexes"                bash -c "node tools/check_indexes.mjs && node tools/check_indexes.test.mjs"
run "rules tests (emulator)"       bash -c "npm ci --prefix firebase/rules_test && npm run test:emulator --prefix firebase/rules_test"
run "no leftover step TODOs"       bash -c '! grep -rn "TODO(step" lib'
run "APK dev"                      flutter build apk --flavor dev -t lib/main_dev.dart
run "APK prod release"             flutter build apk --flavor prod -t lib/main_prod.dart --release

{
  echo
  echo "## Coverage per top-level folder"
  echo
  dart run tools/coverage_summary.dart 2>&1
  echo
  if [ "$FAILED" -eq 0 ]; then
    echo "**Overall: ALL GREEN.** The tag \`phase-1-complete\` may be created after the manual matrix (docs/phase1_manual_test.md) passes."
  else
    echo "**Overall: NOT GREEN.** Do not tag. See the FAIL rows; full logs in $LOG."
  fi
} >> "$OUT"

echo "Wrote $OUT (logs in $LOG)"
exit "$FAILED"
